// Wraps a rendered image (tools/blender/*.py) as a JS module exporting a
// data URI, so the game loads it offline from file:// and in the shared
// artifact without fetching files.
//   node tools/blender/pano-to-module.mjs <in.jpg|png|webp> [out.js] [EXPORT_NAME]
import fs from 'node:fs';
import path from 'node:path';

const [inFile, outFile = 'src/render/assets/hallPanorama.js', name = 'HALL_PANORAMA'] = process.argv.slice(2);
if (!inFile) { console.error('usage: node tools/blender/pano-to-module.mjs <image> [out.js] [EXPORT_NAME]'); process.exit(1); }
const mime = { '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.png': 'image/png', '.webp': 'image/webp' }[path.extname(inFile).toLowerCase()];
if (!mime) { console.error('unsupported image type'); process.exit(1); }
const bytes = fs.readFileSync(inFile);
const out = `// GENERATED by tools/blender/pano-to-module.mjs from a Blender render
// (tools/blender/). ${bytes.length} bytes of ${mime}.
export const ${name} = 'data:${mime};base64,${bytes.toString('base64')}';
`;
fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, out);
console.log(`${outFile}: ${(out.length / 1024).toFixed(0)} KB`);
