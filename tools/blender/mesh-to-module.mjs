// Wraps the compact launcher meshes written by tools/blender/launchers.py as
// one JS module (src/render/assets/launchers.js), so the game loads them
// offline from file:// and in the shared artifact without fetching files.
//   node tools/blender/mesh-to-module.mjs <dir> [out.js]
import fs from 'node:fs';
import path from 'node:path';

const [dir, outFile = 'src/render/assets/launchers.js'] = process.argv.slice(2);
if (!dir) { console.error('usage: node tools/blender/mesh-to-module.mjs <dir> [out.js]'); process.exit(1); }
const meshes = {};
for (const f of fs.readdirSync(dir).filter((x) => x.endsWith('.json')).sort()) {
  const m = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
  meshes[m.id] = m;
}
const ids = Object.keys(meshes);
const out = `// GENERATED by tools/blender/mesh-to-module.mjs from tools/blender/launchers.py.
// ${ids.length} launcher meshes: ${ids.join(', ')}.
// Per mesh: bounds (m), groups by palette slot, base64 data per group:
// int16 positions over the bounds, int8 normals, uint16 indices.
export const LAUNCHER_MESHES = ${JSON.stringify(meshes)};
`;
fs.writeFileSync(outFile, out);
console.log(`${outFile}: ${(out.length / 1024).toFixed(0)} KB, ${ids.length} meshes`);
