// Bit-Beasts. Original spirit creatures bound into spirit chips. Every ability
// is a list of physical "ops" interpreted by game/abilities.js:
//   mods      : timed modifier channels (restitution, friction, damping...)
//   dash      : instantaneous velocity change, paid from spin energy (60% efficient)
//   force     : sustained force (fraction of weight) for a duration, paid from spin
//   shockwave : radial impulse on a nearby opponent, energy drawn from the spirit meter
//   restore   : channelled spin-energy restoration from the spirit meter (interrupted by hits)
//   counter   : timing window; a collision inside it triggers the listed effects
//   nextHit   : arms the next collision with extra lock stress / effects
//   lift      : partial weight relief (less tip drag, easier to knock away)
// Energy injected by spirit-powered ops is booked to the 'ability' ledger.

